'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const sources = ['src/core/ledger.js', 'src/storage/sheets.js', 'apps-script/Code.gs'];
const evidence = JSON.parse(fs.readFileSync(path.join(root, 'fixtures/evidence.json'), 'utf8'));
const source = sources.map(p => fs.readFileSync(path.join(root, p), 'utf8')).join('\n');
const output = path.join(root, 'dist/apps-script');
fs.mkdirSync(output, { recursive: true });
fs.writeFileSync(path.join(output, 'Code.gs'), '// Generated by npm run build:gas. Do not edit.\n' +
  'const BLUE_KITE_EVIDENCE = ' + JSON.stringify(evidence) + ';\n' + source);
fs.copyFileSync(path.join(root, 'apps-script/appsscript.json'), path.join(output, 'appsscript.json'));
console.log('Built dist/apps-script (not uploaded or deployed).');
